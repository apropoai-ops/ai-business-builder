-- 0089 — "לוח לילות": turns the two-table צימר module (0049) into a real
-- property-management core: unit types, maintenance blocks, a booking
-- lifecycle, rate snapshots, a human-readable booking number and an audit log.
--
-- NO GIT IN THIS REPO. Down-path at the bottom.
--
-- ── What already worked and is deliberately NOT touched ─────────────────────
-- 0049 got the hard part right and it stays exactly as it is:
--   · `check_in`/`check_out` are DATE (no time, no zone) → no timezone drift
--   · CHECK (check_out > check_in)
--   · rental_bookings_no_overlap:
--       EXCLUDE USING gist (unit_id WITH =, daterange(check_in, check_out) WITH &&)
--       WHERE (status <> 'cancelled')
--     A real database-level double-booking guarantee on half-open ranges, so
--     back-to-back stays (checkout == next checkin) are legal and overlaps are
--     impossible no matter how many clients race.
--   · RLS: owner-all via is_business_owner(), customer-select-own.
--
-- ── The one structural decision worth reading ───────────────────────────────
-- A maintenance BLOCK is stored as a row in rental_bookings with kind='block',
-- NOT in a separate availability_blocks table.
--
-- Postgres exclusion constraints cannot span two tables. A separate table would
-- mean "a block prevents a booking" is enforced by application code — i.e. it
-- would hold until the first race, the first missed call site, or the first
-- direct PostgREST write. Putting blocks in the same table means the EXISTING
-- constraint above covers them for free, in both directions, forever:
--   booking vs booking · booking vs block · block vs block
-- The price is one discriminator column, and `kind` pays it.
-- ────────────────────────────────────────────────────────────────────────────


-- ══ 1. Unit types (business → unit_type → unit) ════════════════════════════

create table if not exists rental_unit_types (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references businesses(id) on delete cascade,
  name text not null,
  description text,
  sort int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists idx_rental_unit_types_business on rental_unit_types(business_id);

alter table rental_unit_types enable row level security;

do $$ begin
  create policy rental_unit_types_owner_all on rental_unit_types
    for all using (is_business_owner(business_id)) with check (is_business_owner(business_id));
exception when duplicate_object then null; end $$;


-- ══ 2. Units — code, type, amenities ═══════════════════════════════════════
-- `active` stays the unit's status flag; nothing renames it, so every existing
-- reader (listUnits, listPublicUnits, the storefront section) keeps working.

alter table rental_units
  add column if not exists unit_type_id uuid references rental_unit_types(id) on delete set null,
  add column if not exists code text,
  add column if not exists amenities text[];

create index if not exists idx_rental_units_type on rental_units(unit_type_id);


-- ══ 3. Bookings — lifecycle, blocks, money, provenance ═════════════════════

alter table rental_bookings
  -- Booking or maintenance block. See the note at the top.
  add column if not exists kind text not null default 'booking',
  add column if not exists block_reason text,
  -- The nightly rate AS SOLD. Without it, editing a unit's price silently
  -- rewrites the value of every past stay in every revenue report.
  add column if not exists price_per_night numeric not null default 0,
  add column if not exists updated_at timestamptz not null default now(),
  -- Links a stay to the business's own customer record, so nights land in the
  -- existing customer desk instead of a second, parallel guest list.
  add column if not exists crm_customer_id uuid references crm_customers(id) on delete set null,
  add column if not exists source text not null default 'public',
  -- Short number a human can search for and read out on the phone.
  add column if not exists booking_no bigint generated by default as identity,
  -- Unpaid "request to book" holds real dates, so it must expire on its own or
  -- a handful of abandoned requests would silently freeze the calendar.
  add column if not exists hold_expires_at timestamptz,
  add column if not exists cancelled_at timestamptz;

-- Rate snapshot for rows that predate the column: derive from what was charged.
update rental_bookings
   set price_per_night = round(total / greatest(nights, 1), 2)
 where price_per_night = 0 and total > 0;

-- Existing rows are all real bookings made through the public checkout.
update rental_bookings set source = 'public' where source is null;


-- ══ 4. The lifecycle, as a constraint ══════════════════════════════════════
-- The 0049 CHECK allowed only pending/confirmed/cancelled. Replaced, not
-- dropped-and-forgotten, so an invalid status still cannot be written.
--
-- Which statuses HOLD dates is decided by the exclusion constraint's
-- `status <> 'cancelled'`, and that is left alone on purpose:
--   pending   holds — an unconfirmed request must not be double-sold
--   confirmed holds — obviously
--   completed holds — the stay happened; the history is real
--   no_show   holds — the room WAS assigned and could not be resold
--   blocked   holds — that is the entire point of a block
--   cancelled frees — the only status that returns the nights to the pool

alter table rental_bookings drop constraint if exists rental_bookings_status_check;
alter table rental_bookings add constraint rental_bookings_status_check
  check (status in ('pending','confirmed','cancelled','completed','no_show','blocked'));

alter table rental_bookings drop constraint if exists rental_bookings_kind_check;
alter table rental_bookings add constraint rental_bookings_kind_check
  check (kind in ('booking','block'));

alter table rental_bookings drop constraint if exists rental_bookings_source_check;
alter table rental_bookings add constraint rental_bookings_source_check
  check (source in ('public','manual','import'));

-- The two kinds do not share a status vocabulary: a block is never "no_show",
-- and a real booking is never "blocked". Stating it here means no query has to
-- defensively check both columns to know what it is looking at.
alter table rental_bookings drop constraint if exists rental_bookings_kind_status;
alter table rental_bookings add constraint rental_bookings_kind_status check (
  (kind = 'booking' and status in ('pending','confirmed','cancelled','completed','no_show'))
  or
  (kind = 'block' and status in ('blocked','cancelled'))
);

drop trigger if exists trg_rental_bookings_updated_at on rental_bookings;
create trigger trg_rental_bookings_updated_at
  before update on rental_bookings
  for each row execute function set_updated_at();

-- The calendar's primary read is "every stay for this business in this window",
-- and the search screen's is "this guest, by name or phone".
create index if not exists idx_rental_bookings_business_dates
  on rental_bookings(business_id, check_in, check_out);
create index if not exists idx_rental_bookings_status on rental_bookings(business_id, status);
create index if not exists idx_rental_bookings_no on rental_bookings(booking_no);


-- ══ 5. Audit log ═══════════════════════════════════════════════════════════
-- Who changed which stay, from what to what. Written by the service layer on
-- every mutation; never written by a client.

create table if not exists rental_booking_events (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references businesses(id) on delete cascade,
  booking_id uuid references rental_bookings(id) on delete cascade,
  actor_user_id uuid,
  actor_name text,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_rental_events_booking on rental_booking_events(booking_id, created_at desc);
create index if not exists idx_rental_events_business on rental_booking_events(business_id, created_at desc);

alter table rental_booking_events enable row level security;

-- Read-only to the owner: history that the people who make it can rewrite is
-- not history. Every insert goes through createServiceRoleClient().
do $$ begin
  create policy rental_events_owner_select on rental_booking_events
    for select using (is_business_owner(business_id));
exception when duplicate_object then null; end $$;

revoke insert, update, delete on rental_booking_events from anon, authenticated;


